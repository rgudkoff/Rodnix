/* Blink state: inhibit during putc/clear/set_cursor to avoid XOR glitches */
static volatile bool g_blink_inhibit = false;
static uint32_t      g_blink_counter  = 0u;
static uint32_t      g_blink_period   = 50u; /* ticks; default = 100 Hz × 0.5 s */

/* =========================================================================
 * Internal helpers
 * ======================================================================= */

static void draw_glyph(uint32_t col, uint32_t row, uint8_t ch, uint32_t fg, uint32_t bg)
{
    if (!g_disp || !g_disp->fb.virt_base) return;
    if (col >= g_cols || row >= g_rows) return;

    const uint8_t *glyph = g_font8x16[(uint8_t)ch & 0x7Fu];
    uint8_t  *fb    = (uint8_t *)g_disp->fb.virt_base;
    uint32_t  pitch = g_disp->mode.pitch;
    uint32_t  px0   = col * CHAR_W;
    uint32_t  py0   = row * CHAR_H;

    for (uint32_t font_row = 0u; font_row < CHAR_H; font_row++) {
        uint8_t   bits = glyph[font_row];
        uint32_t  py   = py0 + font_row;
        uint32_t *line = (uint32_t *)(fb + (uint64_t)py * pitch);
        for (uint32_t bit = 0u; bit < CHAR_W; bit++) {
            line[px0 + bit] = (bits & (0x80u >> bit)) ? fg : bg;
        }
    }
}

/* Write a character to both the cell buffer and the framebuffer. */
static void cell_put(uint32_t col, uint32_t row, uint8_t ch, uint32_t fg, uint32_t bg)
{
    if (col < GFX_CELL_COLS && row < GFX_CELL_ROWS) {
        g_cells[row][col].ch = ch;
        g_cells[row][col].fg = fg;
        g_cells[row][col].bg = bg;
    }
    draw_glyph(col, row, ch, fg, bg);
}

static void scroll_up(void)
{
    /* Scroll cell buffer up one row. */
    uint32_t r;
    for (r = 1u; r < g_rows && r < GFX_CELL_ROWS; r++) {
        for (uint32_t c = 0u; c < g_cols && c < GFX_CELL_COLS; c++) {
            g_cells[r - 1u][c] = g_cells[r][c];
        }
    }
    /* Clear bottom row in cell buffer. */
    if (g_rows > 0u && g_rows <= GFX_CELL_ROWS) {
        for (uint32_t c = 0u; c < g_cols && c < GFX_CELL_COLS; c++) {
            g_cells[g_rows - 1u][c].ch = 0x20u;
            g_cells[g_rows - 1u][c].fg = g_fg;
            g_cells[g_rows - 1u][c].bg = g_bg;
        }
    }

    /* Scroll framebuffer. */
    if (!g_disp || !g_disp->fb.virt_base) return;
    uint8_t  *fb         = (uint8_t *)g_disp->fb.virt_base;
    uint32_t  pitch      = g_disp->mode.pitch;
    uint32_t  row_bytes  = CHAR_H * pitch;
    uint32_t  total      = g_rows * row_bytes;
    uint32_t  copy_bytes = (g_rows - 1u) * row_bytes;

    uint8_t *dst = fb;
    uint8_t *src = fb + row_bytes;
    for (uint32_t i = 0u; i < copy_bytes; i++) {
        dst[i] = src[i];
    }

    uint32_t *p32  = (uint32_t *)(fb + total - row_bytes);
    uint32_t  npix = (CHAR_H * pitch) / 4u;
    for (uint32_t i = 0u; i < npix; i++) {
        p32[i] = g_bg;
    }
}

/* =========================================================================
 * Cursor — non-destructive XOR block
 * A full-cell invert is much more visible than a 2-scanline underline and
 * makes blinking obvious in framebuffer mode.
 * ======================================================================= */

static void cursor_toggle(void)
{
    if (!g_disp || !g_disp->fb.virt_base) return;
    if (g_cur_col >= g_cols || g_cur_row >= g_rows) return;
    uint8_t  *fb    = (uint8_t *)g_disp->fb.virt_base;
    uint32_t  pitch = g_disp->mode.pitch;
    uint32_t  px0   = g_cur_col * CHAR_W;
    uint32_t  py0   = g_cur_row * CHAR_H;
    for (uint32_t r = 0u; r < CHAR_H; r++) {
        uint32_t *line = (uint32_t *)(fb + (uint64_t)(py0 + r) * pitch);
        for (uint32_t bit = 0u; bit < CHAR_W; bit++) {
            line[px0 + bit] ^= 0x00FFFFFFu;
        }
    }
}

static void cursor_show(void)
{
    if (g_cursor_visible && !g_cursor_drawn) {
        cursor_toggle();
        g_cursor_drawn = true;
    }
}

static void cursor_hide(void)
{
    if (g_cursor_drawn)  { cursor_toggle(); g_cursor_drawn = false; }
}

/* =========================================================================
 * ANSI SGR / CSI dispatch
 * ======================================================================= */

static void ansi_sgr(void)
{
    uint8_t n = (g_ansi_nparams == 0u) ? 1u : g_ansi_nparams;
    for (uint8_t i = 0u; i < n; i++) {
        uint16_t p = (g_ansi_nparams == 0u) ? 0u : g_ansi_params[i];
        if (p == 0u) {
            g_fg = CON_FG_DEFAULT; g_bg = CON_BG_DEFAULT; g_bold = false;
        } else if (p == 1u) {
            g_bold = true;
        } else if (p == 22u) {
            g_bold = false;
        } else if (p >= 30u && p <= 37u) {
            g_fg = g_ansi_pal[(p - 30u) + (g_bold ? 8u : 0u)];
        } else if (p == 39u) {
            g_fg = CON_FG_DEFAULT;
        } else if (p >= 40u && p <= 47u) {
            g_bg = g_ansi_pal[p - 40u];
        } else if (p == 49u) {
            g_bg = CON_BG_DEFAULT;
        } else if (p >= 90u && p <= 97u) {
            g_fg = g_ansi_pal[(p - 90u) + 8u];
        } else if (p >= 100u && p <= 107u) {
            g_bg = g_ansi_pal[(p - 100u) + 8u];
        }
    }
}

static void ansi_dispatch(char cmd)
{
    uint16_t p0 = (g_ansi_nparams > 0u) ? g_ansi_params[0] : 0u;
    uint16_t p1 = (g_ansi_nparams > 1u) ? g_ansi_params[1] : 0u;
    if (g_ansi_private) {
        if (cmd == 'h' || cmd == 'l') {
            for (uint8_t i = 0u; i < g_ansi_nparams; i++) {
                if (g_ansi_params[i] == 12u) {
                    g_cursor_blink_enabled = (cmd == 'h');
                    if (cmd == 'h') {
                        g_blink_counter = 0u;
                    } else if (!g_cursor_drawn && g_cursor_visible) {
                        cursor_show();
                    }
                } else if (g_ansi_params[i] == 25u) {
                    g_cursor_visible = (cmd == 'h');
                    if (!g_cursor_visible) {
                        cursor_hide();
                    }
                }
            }
            if (cmd == 'h' && g_cursor_visible && !g_cursor_drawn) {
                cursor_show();
            }
        }
        return;
    }
    if (g_ansi_has_space && cmd == 'q') {
        if (p0 == 0u || p0 == 1u || p0 == 3u || p0 == 5u) {
            g_cursor_blink_enabled = true;
            g_blink_counter = 0u;
        } else if (p0 == 2u || p0 == 4u || p0 == 6u) {
            g_cursor_blink_enabled = false;
            if (!g_cursor_drawn && g_cursor_visible) {
                cursor_show();
            }
        }
        return;
    }
    switch (cmd) {
    case 'A': { /* cursor up */
        uint16_t n = p0 ? p0 : 1u;
        g_cur_row = (g_cur_row >= (uint32_t)n) ? g_cur_row - n : 0u;
        break; }
    case 'B': { /* cursor down */
        uint16_t n = p0 ? p0 : 1u;
        g_cur_row += n; if (g_cur_row >= g_rows) g_cur_row = g_rows - 1u;
        break; }
    case 'C': { /* cursor right */
        uint16_t n = p0 ? p0 : 1u;
        g_cur_col += n; if (g_cur_col >= g_cols) g_cur_col = g_cols - 1u;
        break; }
    case 'D': { /* cursor left */
        uint16_t n = p0 ? p0 : 1u;
        g_cur_col = (g_cur_col >= (uint32_t)n) ? g_cur_col - n : 0u;
        break; }
    case 'H': case 'f': { /* cursor position — 1-based */
        uint32_t r = p0 ? (uint32_t)(p0 - 1u) : 0u;
        uint32_t c = p1 ? (uint32_t)(p1 - 1u) : 0u;
        g_cur_row = (r < g_rows) ? r : g_rows - 1u;
        g_cur_col = (c < g_cols) ? c : g_cols - 1u;
        break; }
    case 'J': /* erase display */
        if (p0 == 2u) { gfx_console_clear(); }
        break;
    case 'K': /* erase in line */
        if (p0 == 0u) { /* to end */
            for (uint32_t c = g_cur_col; c < g_cols; c++)
                cell_put(c, g_cur_row, 0x20u, g_fg, g_bg);
        } else if (p0 == 1u) { /* to start */
            for (uint32_t c = 0u; c <= g_cur_col; c++)
                cell_put(c, g_cur_row, 0x20u, g_fg, g_bg);
        } else if (p0 == 2u) { /* whole line */
            for (uint32_t c = 0u; c < g_cols; c++)
                cell_put(c, g_cur_row, 0x20u, g_fg, g_bg);
        }
        break;
    case 'm': ansi_sgr(); break;
    default: break;
    }
}

