/* Replay the cell buffer to the framebuffer — called when userspace releases
 * the display so the terminal is restored without any new output. */
static void gfx_console_redraw(gfx_display_t *disp)
{
    if (!disp || !disp->fb.virt_base) return;

    /* Fill background. */
    uint32_t *fb = (uint32_t *)disp->fb.virt_base;
    uint32_t  n  = (disp->mode.pitch / 4u) * disp->mode.height;
    for (uint32_t i = 0u; i < n; i++) {
        fb[i] = g_bg;
    }

    /* Redraw every cell from the buffer. */
    for (uint32_t r = 0u; r < g_rows && r < GFX_CELL_ROWS; r++) {
        for (uint32_t c = 0u; c < g_cols && c < GFX_CELL_COLS; c++) {
            const gfx_cell_t *cell = &g_cells[r][c];
            draw_glyph(c, r, cell->ch, cell->fg, cell->bg);
        }
    }

    /* Restore cursor at the saved position. */
    g_cursor_drawn = false;
    cursor_show();
}

void gfx_console_attach(gfx_display_t *disp)
{
    g_disp = disp;
    if (!disp || !disp->fb.virt_base ||
        disp->mode.width == 0u || disp->mode.height == 0u) {
        g_disp = NULL;
        return;
    }

    g_cols         = disp->mode.width  / CHAR_W;
    g_rows         = disp->mode.height / CHAR_H;
    g_cur_col      = 0u;
    g_cur_row      = 0u;
    g_fg           = CON_FG_DEFAULT;
    g_bg           = CON_BG_DEFAULT;
    g_bold         = false;
    g_ansi_state   = ANSI_NORMAL;
    g_ansi_nparams = 0u;
    g_ansi_private = false;
    g_ansi_has_space = false;
    g_cursor_drawn = false;
    g_cursor_visible = true;
    g_cursor_blink_enabled = true;

    /* Initialise the cell buffer to blank space with default colors. */
    for (uint32_t r = 0u; r < GFX_CELL_ROWS; r++) {
        for (uint32_t c = 0u; c < GFX_CELL_COLS; c++) {
            g_cells[r][c].ch = 0x20u;
            g_cells[r][c].fg = CON_FG_DEFAULT;
            g_cells[r][c].bg = CON_BG_DEFAULT;
        }
    }

    uint32_t *fb = (uint32_t *)disp->fb.virt_base;
    uint32_t  n  = (disp->mode.pitch / 4u) * disp->mode.height;
    for (uint32_t i = 0u; i < n; i++) {
        fb[i] = g_bg;
    }
    cursor_show();

    /* When userspace releases the framebuffer, replay the cell buffer so the
     * terminal is restored without requiring any new output. */
    gfx_set_fb_release_cb(disp, gfx_console_redraw);
}

bool gfx_console_active(void)
{
    return (g_disp != NULL && g_disp->fb.virt_base != NULL &&
            g_disp->fb_owner_refcount == 0);
}

void gfx_console_clear(void)
{
    if (!gfx_console_active()) return;
    g_blink_inhibit = true;
    cursor_hide();

    for (uint32_t r = 0u; r < GFX_CELL_ROWS; r++) {
        for (uint32_t c = 0u; c < GFX_CELL_COLS; c++) {
            g_cells[r][c].ch = 0x20u;
            g_cells[r][c].fg = g_fg;
            g_cells[r][c].bg = g_bg;
        }
    }

    uint32_t *fb = (uint32_t *)g_disp->fb.virt_base;
    uint32_t  n  = (g_disp->mode.pitch / 4u) * g_disp->mode.height;
    for (uint32_t i = 0u; i < n; i++) {
        fb[i] = g_bg;
    }
    g_cur_col = 0u;
    g_cur_row = 0u;
    cursor_show();
    g_blink_inhibit = false;
}

void gfx_console_set_cursor(uint32_t col, uint32_t row)
{
    g_blink_inhibit = true;
    cursor_hide();
    if (col < g_cols) g_cur_col = col;
    if (row < g_rows) g_cur_row = row;
    cursor_show();
    g_blink_inhibit = false;
}

void gfx_console_get_cursor(uint32_t* row, uint32_t* col)
{
    if (row) {
        *row = g_cur_row;
    }
    if (col) {
        *col = g_cur_col;
    }
}

void gfx_console_get_cursor_state(bool* active,
                                  bool* visible,
                                  bool* drawn,
                                  bool* blink_enabled)
{
    if (active) {
        *active = gfx_console_active();
    }
    if (visible) {
        *visible = g_cursor_visible;
    }
    if (drawn) {
        *drawn = g_cursor_drawn;
    }
    if (blink_enabled) {
        *blink_enabled = g_cursor_blink_enabled;
    }
}

uint64_t gfx_console_get_blink_toggle_count(void)
{
    return g_blink_toggle_count;
}

/* Called from console_tick() at a rate set by gfx_console_set_tick_hz(). */
void gfx_console_blink_tick(void)
{
    if (g_blink_inhibit) return;
    if (!gfx_console_active()) return;
    if (!g_cursor_visible) return;
    if (!g_cursor_blink_enabled) return;
    if (++g_blink_counter < g_blink_period) return;
    g_blink_counter = 0u;
    cursor_toggle();
    g_cursor_drawn = !g_cursor_drawn;
    g_blink_toggle_count++;
}

/* Called by the scheduler when the console_tick() call rate is known.
 * hz = how many times per second gfx_console_blink_tick() will be called. */
void gfx_console_set_tick_hz(uint32_t hz)
{
    uint32_t period = (hz > 0u) ? (hz / 2u) : 50u; /* toggle every 500 ms */
    if (period < 1u) { period = 1u; }
    g_blink_period  = period;
    g_blink_counter = 0u;
}

void gfx_console_putc(char c)
{
    if (!gfx_console_active()) return;
    g_blink_inhibit = true;

    unsigned char uc = (unsigned char)c;

    /* ---- ANSI escape parser ---- */
    if (g_ansi_state == ANSI_ESC) {
        g_ansi_state = ANSI_NORMAL;
        if (c == '[') {
            g_ansi_state   = ANSI_CSI;
            g_ansi_nparams = 0u;
            g_ansi_params[0] = 0u;
            g_ansi_private = false;
            g_ansi_has_space = false;
        }
        g_blink_inhibit = false;
        return; /* discard ESC or ESC+[ opener */
    }

    if (g_ansi_state == ANSI_CSI) {
        if (c == '?' && g_ansi_nparams == 0u) {
            g_ansi_private = true;
            g_blink_inhibit = false;
            return;
        }
        if (c == ' ') {
            g_ansi_has_space = true;
            g_blink_inhibit = false;
            return;
        }
        if (uc >= '0' && uc <= '9') {
            if (g_ansi_nparams == 0u) g_ansi_nparams = 1u;
            g_ansi_params[g_ansi_nparams - 1u] =
                g_ansi_params[g_ansi_nparams - 1u] * 10u + (uint16_t)(uc - '0');
            g_blink_inhibit = false;
            return;
        }
        if (c == ';') {
            if (g_ansi_nparams < 8u) {
                g_ansi_nparams++;
                g_ansi_params[g_ansi_nparams - 1u] = 0u;
            }
            g_blink_inhibit = false;
            return;
        }
        /* Final byte: dispatch and return to normal */
        cursor_hide();
        ansi_dispatch(c);
        g_ansi_state = ANSI_NORMAL;
        g_ansi_private = false;
        g_ansi_has_space = false;
        cursor_show();
        g_blink_inhibit = false;
        return;
    }

    if (uc == 0x1Bu) { /* ESC */
        g_ansi_state = ANSI_ESC;
        g_blink_inhibit = false;
        return;
    }

    /* ---- Normal character handling ---- */
    cursor_hide();

    switch (uc) {
    case '\n':
        g_cur_col = 0u;
        g_cur_row++;
        if (g_cur_row >= g_rows) { scroll_up(); g_cur_row = g_rows - 1u; }
        break;

    case '\r':
        g_cur_col = 0u;
        break;

    case '\b':
        if (g_cur_col > 0u) {
            g_cur_col--;
            cell_put(g_cur_col, g_cur_row, 0x20u, g_fg, g_bg);
        }
        break;

    case '\t': {
        uint32_t next_tab = (g_cur_col + 8u) & ~7u;
        while (g_cur_col < next_tab && g_cur_col < g_cols) {
            cell_put(g_cur_col, g_cur_row, 0x20u, g_fg, g_bg);
            g_cur_col++;
        }
        if (g_cur_col >= g_cols) {
            g_cur_col = 0u;
            g_cur_row++;
            if (g_cur_row >= g_rows) { scroll_up(); g_cur_row = g_rows - 1u; }
        }
        break;
    }

    default:
        if (uc < 0x20u || uc == 0x7Fu) break; /* skip non-printable */
        cell_put(g_cur_col, g_cur_row, uc, g_fg, g_bg);
        g_cur_col++;
        if (g_cur_col >= g_cols) {
            g_cur_col = 0u;
            g_cur_row++;
            if (g_cur_row >= g_rows) {
                scroll_up();
                g_cur_row = g_rows - 1u;
            }
        }
        break;
    }

    cursor_show();
    g_blink_inhibit = false;
}
