#define CON_BG_DEFAULT  0x000000u

/* Maximum terminal dimensions (sized for 1024×768 @ 8×16). */
#define GFX_CELL_COLS 128u
#define GFX_CELL_ROWS  48u

/* One terminal cell: the character and its colors at the time of writing. */
